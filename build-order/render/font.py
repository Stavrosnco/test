GLYPHS = {k: [v[i*5:(i+1)*5].ljust(5, ".") for i in range(7)] for k, v in _G.items()}
W, H, ADV = 5, 7, 6

def text_width(s, scale=1):
    return (len(s) * ADV - 1) * scale if s else 0

def draw_text(img, x, y, s, color, scale=1, shadow=(0, 0, 0), outline=False):
    px = img.load()
    w, h = img.size
    o = max(1, scale // 2)
    passes = [(shadow, (dx, dy)) for dx in (-o, 0, o) for dy in (-o, 0, o) if dx or dy] if outline else [(shadow, (scale, scale))]
    passes = ([(shadow, (o + 1, o + 1))] if outline else []) + passes + [(color, (0, 0))]
    for col, (ox, oy) in passes:
        if col is None:
            continue
        cx = x
        for ch in s.upper():
            g = GLYPHS.get(ch, GLYPHS["?"])
            for r, row in enumerate(g):
                for c, on in enumerate(row):
                    if on != "#":
                        continue
                    for dy in range(scale):
                        for dx in range(scale):
                            X, Y = cx + c * scale + dx + ox, y + r * scale + dy + oy
                            if 0 <= X < w and 0 <= Y < h:
                                px[X, Y] = col
            cx += ADV * scale
